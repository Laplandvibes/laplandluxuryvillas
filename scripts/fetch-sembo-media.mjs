#!/usr/bin/env node
/**
 * fetch-sembo-media.mjs — the property's OWN gallery photos from the same Sembo
 * page the fi booking button sends the reader to (Vesa 2026-09-10, hoteldeals:
 * "pakko noissa olla kuvat sieltä syötteestä mistä hinnatkin"; applied to
 * wellness 15.9. and here 19.9.2026).
 *
 * Reads `sembo: ["<hotelCode>", "<polygonId>"]` per property from
 * src/data/properties.ts, opens Sembo's hotel page headless, saves up to SIX
 * gallery candidates as public/images/sembo/<key>-N.webp (1200 px wide, q80)
 * and writes src/data/semboMedia.json (provenance per candidate) plus the page
 * text as evidence under src/data/evidence/.
 *
 * The PICK is made by eye afterwards (scripts/media-contact-sheet.mjs) and
 * written to src/data/semboImagePick.json — never automatically: the first
 * gallery image is aurora on half the hotels (Vesa 11.9.), and the same
 * candidate must not be the one another LV site already uses (1 image = 1 site:
 * hoteldeals uses kakslauttanen #4, arcticTreeHouse #1, levinIglut #1;
 * wellness uses arcticTreeHouse #1).
 *
 * 🔴 Licence: same line as the app on 2026-09-04 and hoteldeals 10.9. — the
 * affiliate programme grants links, not photos; the photos are hotel-supplied,
 * the files are Sembo's. Credit "Kuva: Sembo" on the page; if Sembo/Adtraction
 * objects, delete public/images/sembo/ and the cards fall back to no image.
 *
 * Run: node scripts/fetch-sembo-media.mjs
 */
import { chromium } from "file:///C:/Users/pesol/projects/laplandvibes/node_modules/playwright/index.mjs";
import sharp from "sharp";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(resolve(ROOT, "src/data/properties.ts"), "utf8");
const props = [...src.matchAll(/^\s+(\w+): \{ name: "([^"]+)",[^\n]*?sembo: \["(\d+)", "(\d+)"\]/gm)]
  .map((m) => ({ key: m[1], name: m[2], code: m[3], poly: m[4] }));
if (!props.length) throw new Error("no sembo properties parsed from properties.ts");
const TAIL = "fltr:01000000000000000000000000sug:2ht";
const day = new Date(Date.now() + 45 * 864e5).toISOString().slice(0, 10);
const today = new Date().toISOString().slice(0, 10);
const MAX_IMAGES = 6;

mkdirSync(resolve(ROOT, "public/images/sembo"), { recursive: true });
mkdirSync(resolve(ROOT, "src/data/evidence"), { recursive: true });

const out = {
  _README: "GENERATED by scripts/fetch-sembo-media.mjs from the property's own Sembo.fi page (the fi booking target). Candidates public/images/sembo/<key>-N.webp; the pick lives in semboImagePick.json (by eye). Delete public/images/sembo/ to drop the partner photos (licence note in the script).",
  source: "sembo",
  fetchedAt: today,
  hotels: {},
};

async function download(url) {
  const big = url.replace(/width=\d+&height=\d+/, "width=1600&height=1600");
  const res = await fetch(big, { headers: { Referer: "https://www.sembo.fi/", "User-Agent": "Mozilla/5.0" } });
  if (!res.ok) return null;
  return Buffer.from(await res.arrayBuffer());
}

const browser = await chromium.launch();
const ctx = await browser.newContext({ locale: "fi-FI", viewport: { width: 1280, height: 900 } });
for (const p of props) {
  const url = `https://www.sembo.fi/travel/plan/hotel-selection/h0/hotel-details/${p.code}?pax=rpp&day=${day}&i1=00ot&i2=polygon-id:${p.poly}+${TAIL}&i3=00ot`;
  const page = await ctx.newPage();
  try {
    await page.goto(url, { waitUntil: "domcontentloaded", timeout: 45000 });
    await page.waitForTimeout(8000);
    const r = await page.evaluate((max) => {
      const seen = new Set();
      const srcs = [];
      for (const i of document.querySelectorAll("img")) {
        const s = i.currentSrc || i.src;
        if (!(i.naturalWidth >= 400 && /ImageHandler|travelapi/.test(s))) continue;
        const k = s.replace(/width=\d+&height=\d+/, "");
        if (seen.has(k)) continue;
        seen.add(k);
        srcs.push(s);
        if (srcs.length >= max) break;
      }
      const txt = document.body.innerText;
      const nameLine = (txt.match(/Näytä kaikki \d+ kuvaa\n([^\n]+)\n/) || [])[1] || null;
      const rating = txt.match(/\n(\d[\.,]\d) \/ 10\n(\d+) arvostelua/);
      return { srcs, nameLine, rating: rating ? { score: Number(rating[1].replace(",", ".")), count: Number(rating[2]) } : null, txt };
    }, MAX_IMAGES);
    writeFileSync(resolve(ROOT, `src/data/evidence/sembo-${p.key}-${today}.txt`), `${url}\n\n${r.txt}`);
    if (!r.srcs.length) throw new Error("no gallery image found");
    const candidates = [];
    for (let n = 0; n < r.srcs.length; n++) {
      const buf = await download(r.srcs[n]);
      if (!buf) continue;
      const meta = await sharp(buf).metadata();
      const file = `public/images/sembo/${p.key}-${n + 1}.webp`;
      await sharp(buf).resize({ width: 1200, withoutEnlargement: true }).webp({ quality: 80 }).toFile(resolve(ROOT, file));
      candidates.push({ n: n + 1, file: "/" + file.replace(/^public\//, ""), src: r.srcs[n], w: meta.width, h: meta.height });
    }
    out.hotels[p.key] = { name: p.name, pageName: r.nameLine, hotelCode: p.code, polygonId: p.poly, pageUrl: url, rating: r.rating, candidates, fetchedAt: today };
    console.log(`✓ ${p.key.padEnd(20)} ${r.nameLine ?? "?"} · ${candidates.length} candidates · ${r.rating ? r.rating.score + "/10 (" + r.rating.count + ")" : "no rating"}`);
  } catch (e) {
    console.log(`✗ ${p.key.padEnd(20)} ${e.message.split("\n")[0].slice(0, 120)}`);
  }
  await page.close();
}
await browser.close();
writeFileSync(resolve(ROOT, "src/data/semboMedia.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`wrote src/data/semboMedia.json (${Object.keys(out.hotels).length} hotels)`);
